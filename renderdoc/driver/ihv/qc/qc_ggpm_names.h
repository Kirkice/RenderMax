static const uint32_t kQCGGPMBlockCount = sizeof(kQCGGPMBlocks) / sizeof(kQCGGPMBlocks[0]);

// Resolve a (block name, countable id) pair to the counter's PERF_* style name, or NULL when
// the pair does not exist in the profile.
static inline const char *QCGGPMCounterName(const char *block, uint32_t id)
{
  for(uint32_t b = 0; b < kQCGGPMBlockCount; b++)
  {
    if(strcmp(kQCGGPMBlocks[b].name, block) != 0)
      continue;

    if(id >= kQCGGPMBlocks[b].count)
      return NULL;

    return kQCGGPMBlocks[b].names[id];
  }

  return NULL;
}
