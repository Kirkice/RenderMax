// One hardware block. `glGroup` is the gsl group id (A6xLegacyGslPerfCounterGroupIds)
// and `maxActive` the number of counters the block can hold selected at once
// (A6xMaxActivePerfCounters); both are used to bound one selection pass on the device.
struct QCGGPMBlock
{
  const char *name;
  uint32_t glGroup;
  uint32_t maxActive;
  uint32_t count;
  const char *const *names;
};

