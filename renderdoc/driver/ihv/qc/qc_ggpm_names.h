//
// GENERATED from the per-block counter name pointer arrays that Snapdragon Profiler's
// libGGPM.so ships for the A6x legacy profile (A6xLegacy*PerfCounterNames), cross-checked
// against the counter names the Adreno 610 driver enumerates through
// GL_AMD_performance_monitor on a Redmi Note 8 (ginkgo / trinket).
//
// Index i of kQCGGPMNames_<BLOCK> is Snapdragon Profiler's core::CountableID i for that
// block, which is also the gsl counter id: util::getCounterID() in libGGPM.so is the
// identity function. So a (block, id) pair taken from a libGGPM metric expression resolves
// to a counter name directly, and from there to the driver's own (group, counter) pair by
// name. Do not reorder these arrays - the index IS the id.
//
// Do not hand edit. Regenerate from the plugin's tables if the profile ever changes.

